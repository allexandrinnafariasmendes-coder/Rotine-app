/**
 * Seed exercise bank.
 *
 * Question `contentId`s are derived with the same rule the curriculum builder
 * uses, so a question is always attached to a real topic and the "questions by
 * content" view works without a manual id table.
 */
function cid(subjectId: string, year: SchoolYear, unit: string, content: string): string {
  return `${subjectId}-${year}-${slug(unit)}--${slug(content)}`;
}

